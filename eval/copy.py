"""Every sentence the report prints, in both languages it is read in.

## Why the pairs live together

The report is the site's evidence, and its readers arrive in two languages, so
a report only a subset of them can read is evidence held back. But this is generated
prose that argues with itself — "the prompt did the work; the mechanisms did
not" is a finding, not a label — and a translation kept in a second file drifts
the first time a finding is sharpened and only one copy is edited.

So the two languages sit in one object, on adjacent lines. Changing a finding
means looking at both versions of it, because they are the same expression.

## Why `.format` and not f-strings

The numbers land in different places in the two languages — Turkish puts the
verb last — so the templates carry *named* placeholders and each language
arranges them as its own grammar requires. Positional interpolation would force
Turkish into English word order.

Nothing here computes anything. `eval/metrics.py` owns the arithmetic and
`eval/report.py` owns which sentence applies; this module only knows how to say
it.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import ClassVar, Literal

Lang = Literal["en", "tr"]

LANGS: tuple[Lang, ...] = ("en", "tr")


@dataclass(frozen=True, slots=True)
class Text:
    en: str
    tr: str

    def of(self, lang: Lang) -> str:
        return self.tr if lang == "tr" else self.en

    def format(self, lang: Lang, /, **values: object) -> str:
        return self.of(lang).format(**values)


